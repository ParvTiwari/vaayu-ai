"""
Citizen Advisory Agent — a DETERMINISTIC CPCB health-guidance lookup wrapped in
an LLM narrative layer for multilingual, voice-ready citizen advisories.

TRUST MODEL (why this is split in two)
--------------------------------------
The health facts come from a hardcoded table sourced from CPCB's published AQI
health-impact guidance (`HEALTH_GUIDANCE`) — analogous to AgriBloom's DISCLAIMERS
dict. This is the ground truth the citizen relies on, so it is NEVER generated by
an LLM: the model cannot hallucinate a wrong "it's safe to jog" for a Severe day.
The LLM's only job is to *rephrase and localize* that fixed guidance into a
short, friendly advisory in the requested language — it is explicitly forbidden
from inventing AQI numbers or health claims. If no LLM is configured (or the call
fails), we fall back to the deterministic guidance text directly, so the endpoint
always returns real, safe advice.

LANGUAGE HANDLING
-----------------
We ask the LLM to respond *directly* in the requested language (single call),
rather than generating English and translating after — simpler and avoids a
second round-trip / a second place for errors to creep in. The deterministic
fallback ships hardcoded English + Hindi guidance; other languages (e.g. Kannada)
are only available via the LLM path and fall back to English guidance text
otherwise (clearly noted in the advisory).

SOURCE CITATION (trust-transparency, informed by the Drishti submission)
------------------------------------------------------------------------
Every advisory returns `sources_cited` with the exact station id/name, the
reading timestamp, and the AQI value/category it was based on — so a citizen (or
an auditor) can trace the advice back to a real reading.
"""
